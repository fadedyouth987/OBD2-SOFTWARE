import { launch, shot, signup, connectAdapter, nav, BASE } from './lib.mjs';
const { browser, page, errors } = await launch();
const log = (...a) => console.log('•', ...a);
try {
  await signup(page, 'comm');
  await page.waitForTimeout(2500);
  await shot(page, '01-home-community');
  log('signed up, home');
  await page.goto(BASE + '/devices');
  await page.getByText('virtual-ford-falcon-ba', { exact: true }).waitFor({ timeout: 20000 });
  await page.waitForTimeout(800);
  await shot(page, '02-devices-daemon-ready');
  log('daemon ready + adapters listed');
  await connectAdapter(page, 'virtual-ford-falcon-ba');
  log('connected Silent');
  await nav(page, '/jobs/new');
  await page.getByLabel('VIN').waitFor();
  await page.waitForFunction(() => document.querySelector('input[id]') && [...document.querySelectorAll('input')].some((i) => i.value === '6FPAAAJGSW8B12345'), null, { timeout: 15000 });
  await page.getByLabel('Vehicle', { exact: true }).fill('2004 Ford Falcon BA XR6 (sim)');
  await page.getByLabel('Odometer (km)').fill('214500');
  await page.getByLabel('Customer complaint').fill('Rough idle, check engine light on');
  await shot(page, '03-new-job-vin-read');
  await page.getByRole('button', { name: 'Start job and scan' }).click();
  await page.waitForURL(/\/jobs\/[0-9a-f-]+\?scan=1/, { timeout: 20000 });
  await page.getByText('P0171').first().waitFor({ timeout: 30000 });
  await page.getByText('C1145').first().waitFor({ timeout: 30000 });
  await page.waitForTimeout(1500);
  await shot(page, '04-job-overview-scanned');
  const clearDisabled = await page.getByRole('button', { name: 'Clear codes' }).isDisabled();
  log('scan done; Clear codes disabled on Community =', clearDisabled);
  const jobUrl = page.url().split('?')[0]; const jobPath = new URL(jobUrl).pathname;
  await nav(page, jobPath + '/copilot');
  await page.getByRole('button', { name: 'Diagnose' }).click();
  await page.getByText(/confidence/).first().waitFor({ timeout: 20000 });
  await shot(page, '05-copilot-diagnosed');
  log('diagnosed');
  await nav(page, jobPath + '/live');
  await page.getByText('Engine speed').first().waitFor({ timeout: 15000 });
  await page.getByRole('button', { name: 'Record to job' }).click();
  await page.waitForTimeout(7000);
  await shot(page, '06-live-data-recording');
  await page.getByRole('button', { name: 'Stop recording' }).click();
  await page.waitForTimeout(1500);
  log('live recorded');
  await nav(page, jobPath + '/modules');
  await page.getByRole('button', { name: 'Read identification' }).click();
  await page.waitForTimeout(6000);
  await shot(page, '07-modules-ident');
  await nav(page, jobPath + '/service');
  await page.getByText('Oil service reset', { exact: false }).first().waitFor({ timeout: 15000 }).catch(() => {});
  await page.waitForTimeout(1500);
  await shot(page, '08-service-community-locked');
  await nav(page, jobPath + '/can');
  await page.waitForTimeout(1500);
  await shot(page, '09-can-locked');
  await nav(page, jobPath + '/closeout');
  await page.getByLabel(/What you found/).fill('Lean codes both banks; unmetered air leak at intake boot.');
  await page.getByLabel(/Repair carried out/).fill('Replaced cracked intake boot, cleared codes, road tested.');
  await page.getByLabel(/Parts replaced/).fill('Intake air boot');
  await page.getByRole('button', { name: 'Close job' }).click();
  await page.getByText(/Job closed/).waitFor({ timeout: 15000 });
  await shot(page, '10-closeout-done');
  await page.goto(jobUrl.replace('/jobs/', '/report/'));
  await page.getByText('Fault codes found').waitFor({ timeout: 15000 });
  await page.waitForTimeout(800);
  await shot(page, '11-customer-report');
  log('closed + report');
  await nav(page, '/key-programming');
  await page.waitForTimeout(2500);
  await shot(page, '12-key-programming-gates');
  await nav(page, '/workshop/billing');
  await page.waitForTimeout(2500);
  await shot(page, '13-billing');
  console.log('JOB', jobUrl);
} catch (e) {
  console.log('FAIL', e.message.split('\n')[0]);
  await shot(page, 'zz-fail-community');
} finally {
  console.log('console errors:', errors.length ? errors.slice(0, 15) : 'none');
  await browser.close();
}
