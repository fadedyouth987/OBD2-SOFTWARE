import { launch, shot, signup, connectAdapter, nav, confirmGated, apiCall, BASE } from './lib.mjs';
const { browser, page, errors } = await launch();
const log = (...a) => console.log('•', ...a);
try {
  await signup(page, 'ws');
  const g = await apiCall(page, '/api/v1/auth/dev-grant-plan', { tier: 'WORKSHOP', immo_entitled: true });
  log('grant', g.status);
  await page.goto(BASE + '/devices');
  await page.getByText('Lease: Workshop').waitFor({ timeout: 30000 });
  log('lease synced to Workshop');
  await connectAdapter(page, 'virtual-ford-falcon-ba', { active: true });
  await page.getByText(/Active/).first().waitFor();
  await shot(page, '20-devices-workshop-active');
  await nav(page, '/jobs/new');
  await page.waitForFunction(() => [...document.querySelectorAll('input')].some((i) => i.value === '6FPAAAJGSW8B12345'), null, { timeout: 15000 });
  await page.getByLabel('Vehicle', { exact: true }).fill('2004 Ford Falcon BA XR6 (sim)');
  await page.getByRole('button', { name: 'Start job and scan' }).click();
  await page.waitForURL(/\/jobs\/[0-9a-f-]+\?scan=1/, { timeout: 20000 });
  await page.getByText('P0171').first().waitFor({ timeout: 30000 });
  await page.waitForTimeout(1000);
  const jobPath = new URL(page.url()).pathname;
  await page.getByRole('button', { name: 'Clear codes' }).click();
  await page.getByRole('alertdialog').waitFor();
  await shot(page, '21-clear-codes-safety-modal', false);
  await confirmGated(page);
  await page.getByText(/cleared|No codes stored|Codes cleared/i).first().waitFor({ timeout: 40000 });
  await page.waitForTimeout(3000);
  await page.locator('td', { hasText: /cleared$/ }).first().waitFor({ timeout: 10000 });
  await shot(page, '22-codes-cleared-rescan');
  log('cleared');
  await nav(page, jobPath + '/service');
  const oil = page.locator('div,li,article').filter({ has: page.getByText('Oil Service / Maintenance Reset', { exact: true }) }).filter({ has: page.getByRole('button', { name: 'Run' }) }).last();
  await oil.getByRole('button', { name: 'Run' }).click();
  await page.getByRole('alertdialog').waitFor();
  await shot(page, '23-service-oil-reset-modal', false);
  await confirmGated(page);
  await page.getByText(/completed|Done|finished/i).first().waitFor({ timeout: 40000 });
  await page.waitForTimeout(1000);
  await shot(page, '24-service-oil-reset-done');
  log('oil reset done');
  await nav(page, jobPath + '/can');
  await page.waitForTimeout(6000);
  await shot(page, '25-can-studio-frames');
  log('can studio');
  await nav(page, jobPath + '/closeout');
  await page.waitForTimeout(1500);
  await shot(page, '26-closeout-cleared-preticked');
  await nav(page, '/key-programming');
  await page.waitForTimeout(2500);
  await shot(page, '27-key-programming-workshop-flag-off');
  await nav(page, '/workshop');
  await page.waitForTimeout(2000);
  await shot(page, '28-workshop');
} catch (e) {
  console.log('FAIL', e.message.split('\n')[0]);
  await shot(page, 'zz-fail-workshop');
} finally {
  console.log('console errors:', errors.length ? errors.slice(0, 15) : 'none');
  await browser.close();
}
