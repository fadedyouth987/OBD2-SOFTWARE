"""Shared token fixture: ``signing.py`` signs, the Rust daemon verifies (Task 2.2 gate).

``packages/schemas/fixtures/signing/cloud_tokens.json`` is built here from a
fixed, TEST-ONLY seed with the clock pinned, using the production issuing
functions. Ed25519 signatures are deterministic, so the file is reproducible:
``test_signing_fixture.py`` fails if it drifts from ``signing.py``, and
``apps/edge-daemon/tests/cloud_token_fixture.rs`` verifies every token with the
fixture key pinned the way ``scripts/export_cloud_keys.py`` pins a real one.

Regenerate: ``cd services/cloud-api && uv run python -m tests.signing_fixture --write``
"""

from __future__ import annotations

import json
import os
import sys
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path
from unittest import mock

from app.services import signing

FIXTURE = (
    Path(__file__).resolve().parents[3]
    / "packages"
    / "schemas"
    / "fixtures"
    / "signing"
    / "cloud_tokens.json"
)

# TEST ONLY. Public in this repository: never configure or pin it anywhere else.
SEED_HEX = bytes(range(1, 33)).hex()
OTHER_SEED_HEX = bytes(range(101, 133)).hex()
KID = "fixture-2026-11"
NOW = 1_795_000_000
TENANT = "5f0c7a52-3d0e-4a8e-9b1c-2a6f3d4e5b60"
USER = "0b9e8d7c-6a5b-4c3d-8e2f-1a0b9c8d7e6f"
ORIGIN = "http://localhost:3000"
DONGLE = "edge-fixture-01"


@contextmanager
def signer(seed_hex: str = SEED_HEX, kid: str = KID, now: int = NOW) -> Iterator[None]:
    """The real issuing functions with a pinned key, kid and clock."""
    with (
        mock.patch.dict(os.environ, {"CLOUD_SIGNING_PRIVATE_KEY_HEX": seed_hex}),
        mock.patch.object(signing, "PINNED_KID", kid),
        mock.patch.object(signing.time, "time", return_value=float(now)),
    ):
        yield


def _lease(**kw) -> str:
    args = dict(
        tenant_id=TENANT,
        user_id=USER,
        tier="WORKSHOP",
        aasra_verified=True,
        dongle_id=DONGLE,
        lease_version=3,
    )
    args.update(kw)
    return signing.issue_edge_lease(**args)["token"]


def _immo(**kw) -> str:
    args = dict(
        session_id="immo-sess-1",
        jti="immo-jti-1",
        vin="WBAVB11060PT00001",
        device_id=DONGLE,
        device_tier="WORKSHOP",
        oem="BMW",
        operation="KEY_LEARN",
    )
    args.update(kw)
    return signing.issue_immo_lease(TENANT, USER, **args)["token"]


def build() -> dict:
    with signer():
        public_key_hex = signing.public_key_raw().hex()
        lease = _lease()
        pairing = signing.issue_pairing_jwt(TENANT, USER, ORIGIN)["token"]
        immo = _immo()
        session = signing.issue_session_jwt(TENANT, USER)["access_token"]
    with signer(now=NOW - 72 * 3600 - 301):
        expired = _lease(tier="COMMUNITY")  # 72 h lease that ended 301 s ago
    with signer(seed_hex=OTHER_SEED_HEX):
        impostor = _lease()  # right kid, wrong key
    with signer(seed_hex=OTHER_SEED_HEX, kid="unknown-kid"):
        stranger = _lease()
    return {
        "comment": (
            "Generated by services/cloud-api/tests/signing_fixture.py with a TEST-ONLY key. "
            "Never pin public_key_hex outside tests."
        ),
        "kid": KID,
        "public_key_hex": public_key_hex,
        "now": NOW,
        "origin": ORIGIN,
        "valid": {"lease": lease, "pairing": pairing, "immo_lease": immo},
        "expected": {
            "lease": {
                "tenant_id": TENANT,
                "user_id": USER,
                "tier": "WORKSHOP",
                "features": ["UDS_ACTIVE", "CAN_RE_PRO", "J2534"],
                "aasra_verified": True,
                "rcid": DONGLE,
                "lease_ver": 3,
                "exp": NOW + signing.PAID_LEASE_TTL_S,
            },
            "pairing": {"user_id": USER, "tenant_id": TENANT},
            "immo_lease": {"session_id": "immo-sess-1", "jti": "immo-jti-1", "oem": "BMW"},
        },
        "rejected": {
            "lease_signed_by_other_key": impostor,
            "lease_unknown_kid": stranger,
            "lease_expired": expired,
            "pairing_as_lease": pairing,
            "session_as_lease": session,
            "lease_as_pairing": lease,
            "lease_as_immo": lease,
            "immo_as_diagnostic_lease": immo,
        },
    }


def render() -> str:
    return json.dumps(build(), indent=2) + "\n"


if __name__ == "__main__":
    if "--write" in sys.argv:
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(render())
        print(f"wrote {FIXTURE}")
    else:
        print(render(), end="")
