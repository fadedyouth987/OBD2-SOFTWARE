#!/usr/bin/env node
// TypeScript side of the shared-contract codegen (A-DX-3, A-DX-2).
//
// Reads the JSON Schemas in packages/schemas/ and writes:
//   apps/web/src/types/edge-protocol.ts        Zod validators + inferred types
//   apps/web/src/types/safety-policy-schema.ts  Zod validator for safety_policy.json
//   docs/protocol.md                            protocol reference
//
// Usage: node scripts/codegen.mjs [--check]
// --check exits 1 if any checked-in output differs from fresh output (CI drift gate).
// The Rust side is tools/codegen; `just codegen` runs both.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { jsonSchemaToZod } from "json-schema-to-zod";
import * as prettier from "prettier";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");
const root = join(pkg, "../..");
const check = process.argv.includes("--check");

const readJson = (p) => JSON.parse(readFileSync(join(pkg, p), "utf8"));

/** Definition names in dependency order, so each `const` is declared before use. */
function topoOrder(definitions) {
  const order = [];
  const state = new Map();
  const refsOf = (node, out = new Set()) => {
    if (Array.isArray(node)) node.forEach((n) => refsOf(n, out));
    else if (node && typeof node === "object") {
      if (typeof node.$ref === "string") out.add(node.$ref.replace("#/definitions/", ""));
      Object.values(node).forEach((n) => refsOf(n, out));
    }
    return out;
  };
  const visit = (name) => {
    if (state.get(name) === "done") return;
    if (state.get(name) === "visiting") throw new Error(`schema cycle at ${name}`);
    state.set(name, "visiting");
    for (const dep of refsOf(definitions[name])) visit(dep);
    state.set(name, "done");
    order.push(name);
  };
  Object.keys(definitions).sort().forEach(visit);
  return order;
}

/** One `export const` per definition; `$ref`s become references to those names. */
function zodModule(schema, { header, rootName, rootDiscriminator }) {
  const defs = schema.definitions ?? {};
  const parserOverride = (node) => {
    if (typeof node.$ref === "string") return node.$ref.replace("#/definitions/", "");
    return undefined;
  };
  const toZod = (node) =>
    jsonSchemaToZod(node, { module: "none", zodVersion: 4, parserOverride, noImport: true });

  const lines = [header, 'import { z } from "zod";', ""];
  for (const name of topoOrder(defs)) {
    const def = defs[name];
    if (def.description) lines.push(`/** ${def.description.replace(/\*\//g, "*\\/")} */`);
    lines.push(`export const ${name} = ${toZod(def)};`);
    lines.push(`export type ${name} = z.infer<typeof ${name}>;`, "");
  }

  if (schema.description) lines.push(`/** ${schema.description} */`);
  if (rootDiscriminator) {
    const variants = schema.oneOf.map((v) => v.$ref.replace("#/definitions/", ""));
    lines.push(
      `export const ${rootName} = z.discriminatedUnion(${JSON.stringify(rootDiscriminator)}, [${variants.join(", ")}]);`,
    );
  } else {
    const { definitions: _d, $schema: _s, $id: _i, title: _t, ...body } = schema;
    lines.push(`export const ${rootName} = ${toZod(body)};`);
  }
  lines.push(`export type ${rootName} = z.infer<typeof ${rootName}>;`, "");
  return lines.join("\n");
}

function edgeExtras(schema) {
  const variants = schema.oneOf.map((v) => v.$ref.replace("#/definitions/", ""));
  return [
    `/** Wire protocol version, from \`x-protocol-version\` in edge_ws.schema.json. */`,
    `export const PROTOCOL_VERSION = ${JSON.stringify(schema["x-protocol-version"])};`,
    "",
    `/** Every message type in the envelope. */`,
    `export const MESSAGE_TYPES = ${JSON.stringify(variants)} as const;`,
    `export type MessageType = (typeof MESSAGE_TYPES)[number];`,
    "",
    `/** Each request type and the response it expects; any request may also get ErrorResponse. */`,
    `export const REQUEST_RESPONSE = ${JSON.stringify(schema["x-request-response"])} as const satisfies Partial<Record<MessageType, MessageType>>;`,
    "",
  ].join("\n");
}

function fieldType(node) {
  if (node.$ref) return `\`${node.$ref.replace("#/definitions/", "")}\``;
  if (node.anyOf) return node.anyOf.map(fieldType).join(" or ");
  if (node.enum) return node.enum.map((v) => `\`${v}\``).join(" / ");
  if (node.type === "array") return `array of ${fieldType(node.items)}`;
  return [node.type].flat().join(" or ");
}

function protocolDoc(schema) {
  const defs = schema.definitions;
  const variants = schema.oneOf.map((v) => v.$ref.replace("#/definitions/", ""));
  const pairs = schema["x-request-response"];
  const out = [
    "<!-- @generated by packages/schemas/scripts/codegen.mjs from edge_ws.schema.json -- DO NOT EDIT. -->",
    "",
    "# Edge WebSocket protocol reference",
    "",
    `Protocol version **${schema["x-protocol-version"]}**. ${schema.description}`,
    "",
    "Every message is a JSON object with a `type` field naming one of the messages below. Requests carry a client-generated `request_id`; the response, or an `ErrorResponse`, echoes it. Gated diagnostic services are listed in [`safety_policy.json`](../packages/schemas/safety_policy.json); error hints are in [`error_hints.json`](../packages/schemas/error_hints.json).",
    "",
    "## Requests and responses",
    "",
    "| Request | Response |",
    "| --- | --- |",
    ...Object.entries(pairs).map(([req, resp]) => `| \`${req}\` | \`${resp}\` or \`ErrorResponse\` |`),
    "",
    "## Messages",
    "",
  ];
  for (const name of variants) {
    const def = defs[name];
    out.push(`### ${name}`, "");
    if (def.description) out.push(def.description, "");
    out.push("| Field | Type | Notes |", "| --- | --- | --- |");
    for (const [field, node] of Object.entries(def.properties)) {
      if (field === "type") continue;
      const notes = (node.description ?? "").replace(/\|/g, "\\|");
      out.push(`| \`${field}\` | ${fieldType(node)} | ${notes} |`);
    }
    out.push("");
  }
  out.push("## Shared types", "");
  for (const [name, def] of Object.entries(defs)) {
    if (variants.includes(name)) continue;
    const detail = def.enum
      ? def.enum.map((v) => `\`${v}\``).join(", ")
      : def.pattern
        ? `string matching \`${def.pattern}\``
        : def.type === "object"
          ? `object: ${Object.keys(def.properties).map((f) => `\`${f}\``).join(", ")}`
          : [def.type].flat().join(" or ");
    out.push(`- **${name}**: ${detail}.${def.description ? ` ${def.description}` : ""}`);
  }
  out.push("");
  return out.join("\n");
}

const HEADER = (src) =>
  `// @generated by packages/schemas/scripts/codegen.mjs from packages/schemas/${src} -- DO NOT EDIT.\n// Edit the schema, then run \`just codegen\`.`;

const edge = readJson("edge_ws.schema.json");
const policy = readJson("safety_policy.schema.json");

const outputs = [
  {
    path: "apps/web/src/types/edge-protocol.ts",
    parser: "typescript",
    content:
      zodModule(edge, {
        header: HEADER("edge_ws.schema.json"),
        rootName: "EdgeMessage",
        rootDiscriminator: "type",
      }) + edgeExtras(edge),
  },
  {
    path: "apps/web/src/types/safety-policy-schema.ts",
    parser: "typescript",
    content: zodModule(policy, {
      header: HEADER("safety_policy.schema.json"),
      rootName: "SafetyPolicy",
    }),
  },
  { path: "docs/protocol.md", parser: "markdown", content: protocolDoc(edge) },
];

let drift = false;
for (const { path, parser, content } of outputs) {
  const fresh = await prettier.format(content, { parser, printWidth: 100 });
  const target = join(root, path);
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // first run
  }
  if (current === fresh) continue;
  if (check) {
    console.error(`codegen: ${path} is out of date; run \`just codegen\``);
    drift = true;
  } else {
    writeFileSync(target, fresh);
    console.log(`codegen: wrote ${relative(root, target)}`);
  }
}
process.exit(drift ? 1 : 0);
