#!/usr/bin/env python3
"""Export Ed25519 cloud verifying key(s) into apps/edge-daemon/src/auth/cloud_keys.rs,
and with --kotlin-out into the Android app's CloudKeys.kt as well.

Usage:
  python3 scripts/export_cloud_keys.py --kid cloud-2026-11 --pubkey-hex <64-hex-chars>
  python3 scripts/export_cloud_keys.py --key cloud-2027-05=<hex> --key cloud-2026-11=<hex>
  python3 scripts/export_cloud_keys.py --pubkey-hex <hex> --kotlin-out \
      apps/android/app/src/main/java/au/com/rootcauseobd/fleet/data/CloudKeys.kt

Pass --key more than once during a signing-key rotation, newest first, so daemons
trust both the new and the old key until every lease signed by the old one has
expired (docs/runbooks/signing-key-rotation.md).

Safe pinning:
  CLOUD_KEYS is empty by default, which is the secure COMMUNITY-only mode.
  Only pin the public half of a production key whose private seed lives in a
  secret manager as CLOUD_SIGNING_PRIVATE_KEY_HEX. Never pin a development
  key, and never commit a private key. Pinning a key means every valid lease
  signed by that key is accepted on the vehicle.
"""
from __future__ import annotations

import argparse
from pathlib import Path

TEMPLATE = """//! Pinned cloud signing keys (generated by scripts/export_cloud_keys.py).
//! No private key is ever stored in this repository.

use ed25519_dalek::VerifyingKey;

pub struct CloudKey {{
    pub kid: &'static str,
    pub public_key: [u8; 32],
}}

pub const CLOUD_KEYS: &[CloudKey] = &[
{entries}];

#[derive(Clone, Debug, Default)]
pub struct KeyRing {{
    keys: Vec<(String, VerifyingKey)>,
}}

impl KeyRing {{
    pub fn production() -> Self {{
        Self::from_raw(CLOUD_KEYS.iter().map(|k| (k.kid.to_owned(), k.public_key)))
            .expect("pinned cloud keys are valid Ed25519 points")
    }}

    pub fn from_raw(
        keys: impl IntoIterator<Item = (String, [u8; 32])>,
    ) -> Result<Self, ed25519_dalek::SignatureError> {{
        let keys = keys
            .into_iter()
            .map(|(kid, raw)| Ok((kid, VerifyingKey::from_bytes(&raw)?)))
            .collect::<Result<_, ed25519_dalek::SignatureError>>()?;
        Ok(Self {{ keys }})
    }}

    pub fn get(&self, kid: &str) -> Option<&VerifyingKey> {{
        self.keys.iter().find(|(k, _)| k == kid).map(|(_, v)| v)
    }}

    pub fn is_empty(&self) -> bool {{
        self.keys.is_empty()
    }}
}}
"""


KOTLIN_TEMPLATE = """package au.com.rootcauseobd.fleet.data

/**
 * Pinned cloud signing keys (generated by scripts/export_cloud_keys.py --kotlin-out).
 *
 * Same rule as the edge daemon's `cloud_keys.rs`: only the public half of a
 * production key. Debug builds may also trust the configured server's JWKS
 * (see [CloudAccount]). No private key is in this repository.
 */
object CloudKeys {{
    /** kid → 64-hex Ed25519 public key, newest first. */
    val PINNED: Map<String, String> = linkedMapOf(
{entries}    )

    fun pinned(): Map<String, ByteArray> = PINNED.mapValues {{ (_, hex) -> LicenceVerifier.hexKey(hex) }}
}}
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--kid", default="cloud-2026-11")
    parser.add_argument("--pubkey-hex", help="32-byte Ed25519 public key in hex (64 chars)")
    parser.add_argument(
        "--key",
        action="append",
        default=[],
        metavar="KID=HEX",
        help="A key to pin; repeat during rotation, newest first",
    )
    parser.add_argument("--out", default="apps/edge-daemon/src/auth/cloud_keys.rs")
    parser.add_argument(
        "--kotlin-out",
        help="Also write the Android app's CloudKeys.kt with the same keys",
    )
    args = parser.parse_args()

    pairs: list[tuple[str, str]] = []
    for item in args.key:
        kid, sep, hexkey = item.partition("=")
        if not sep or not kid or not hexkey:
            raise SystemExit(f"--key must look like KID=HEX, got {item!r}")
        pairs.append((kid.strip(), hexkey.strip()))
    if args.pubkey_hex:
        pairs.append((args.kid, args.pubkey_hex.strip()))
    if not pairs:
        raise SystemExit("Give --pubkey-hex or at least one --key KID=HEX")
    if len({kid for kid, _ in pairs}) != len(pairs):
        raise SystemExit("Each kid can be pinned once")

    entries = []
    for kid, hexkey in pairs:
        raw = bytes.fromhex(hexkey)
        if len(raw) != 32:
            raise SystemExit(f"{kid}: expected a 32-byte Ed25519 public key, got {len(raw)} bytes")
        byte_list = ", ".join(f"0x{b:02x}" for b in raw)
        entries.append(f'    CloudKey {{\n        kid: "{kid}",\n        public_key: [{byte_list}],\n    }},\n')
    Path(args.out).write_text(TEMPLATE.format(entries="".join(entries)), encoding="utf-8")
    print(f"Pinned {', '.join(kid for kid, _ in pairs)} -> {args.out}")
    if args.kotlin_out:
        kt = "".join(f'        "{kid}" to "{hexkey.lower()}",\n' for kid, hexkey in pairs)
        Path(args.kotlin_out).write_text(KOTLIN_TEMPLATE.format(entries=kt), encoding="utf-8")
        print(f"Pinned {', '.join(kid for kid, _ in pairs)} -> {args.kotlin_out}")
    print(
        "WARNING: this key will be trusted on the vehicle. Use a production "
        "public key only; keep CLOUD_KEYS empty for the safe COMMUNITY default."
    )


if __name__ == "__main__":
    main()
